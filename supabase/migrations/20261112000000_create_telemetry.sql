-- 1. Create Telemetry Table
create table if not exists telemetry (
  id bigint generated by default as identity primary key,
  created_at timestamptz default now() not null,
  temp numeric(4,1),
  hum numeric(4,1),
  aqi integer,
  co_gas integer,
  dust numeric(5,1)
);

-- 2. Create Index on created_at for fast time-series queries
create index if not exists idx_telemetry_created_at on telemetry (created_at desc);

-- 3. Enable Row Level Security (RLS)
alter table telemetry enable row level security;

-- 4. Policy: Allow ESP32 anonymous insertion using anon key
drop policy if exists "Allow anonymous insert" on telemetry;
create policy "Allow anonymous insert" 
on telemetry for insert 
to anon 
with check (true);

-- 5. Policy: Allow Web Dashboard anonymous read for historical backfill
drop policy if exists "Allow anonymous read" on telemetry;
create policy "Allow anonymous read" 
on telemetry for select 
to anon 
using (true);
